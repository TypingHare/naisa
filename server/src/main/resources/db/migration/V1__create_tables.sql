-- Sets the `updated_at` to the current timestamp. 
CREATE FUNCTION set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at := statement_timestamp();
    RETURN NEW;
END;
$$;

CREATE TABLE clients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    api_key VARCHAR(36) NOT NULL UNIQUE DEFAULT gen_random_uuid()::TEXT
);
COMMENT ON TABLE clients
IS 'Clients authorized to access the API';
COMMENT ON COLUMN clients.api_key
IS 'Unique API key for authenticating the client';


CREATE TABLE venues (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    address VARCHAR(255) NOT NULL,
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    timezone VARCHAR(32) NOT NULL,

    CONSTRAINT venues_latitude_range CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT venues_longitude_range CHECK (longitude BETWEEN -180 AND 180)
);
COMMENT ON COLUMN venues.name
IS 'Name of the venue';
COMMENT ON COLUMN venues.address
IS 'USPS address of the venue';
COMMENT ON COLUMN venues.latitude
IS 'Latitude of the venue location';
COMMENT ON COLUMN venues.longitude
IS 'Longitude of the venue location';
COMMENT ON COLUMN venues.timezone
IS 'IANA time zone identifier of the venue';


CREATE TABLE sports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(32) NOT NULL
);
COMMENT ON COLUMN sports.name
IS 'Name of the sport in title case; for example: Basketball, Table Tennis';


CREATE TABLE venue_sports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venue_id BIGINT NOT NULL REFERENCES venues(id),
    sport_id BIGINT NOT NULL REFERENCES sports(id),
    price DECIMAL(12, 2) NOT NULL,
    is_indoor BOOLEAN NOT NULL,

    CONSTRAINT venue_sports_price_range CHECK (price >= 0),
    CONSTRAINT venue_sports_pair_unique UNIQUE (venue_id, sport_id)
);
COMMENT ON TABLE venue_sports
IS 'Sports offered at each venue';
COMMENT ON COLUMN venue_sports.price
IS 'General price of the sport in the venue in dollars';
COMMENT ON COLUMN venue_sports.is_indoor
IS 'Whether the sport field is indoor';

CREATE TABLE opening_intervals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venue_id BIGINT NOT NULL REFERENCES venues(id),
    day_of_week VARCHAR(9) NOT NULL,
    opens_at TIME NOT NULL,
    closes_at TIME NOT NULL,

    CONSTRAINT opening_intervals_day_of_week_enum CHECK (day_of_week IN (
        'MONDAY',
        'TUESDAY',
        'WEDNESDAY',
        'THURSDAY',
        'FRIDAY',
        'SATURDAY',
        'SUNDAY'
    ))
);


CREATE TABLE reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT NOT NULL REFERENCES clients(id),
    external_user_id VARCHAR(128) NOT NULL,
    venue_id BIGINT NOT NULL REFERENCES venues(id),
    sport_id BIGINT REFERENCES sports(id),
    rating SMALLINT NOT NULL,
    comment_content TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT current_timestamp,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT current_timestamp,

    CONSTRAINT reviews_rating_range CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT fk_reviews_sport_venue
        FOREIGN KEY (venue_id, sport_id)
        REFERENCES venue_sports(venue_id, sport_id)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);
COMMENT ON TABLE reviews
IS 'Ratings and comments submitted by end users about venues';
COMMENT ON COLUMN reviews.client_id
IS 'Client that provides the review';
COMMENT ON COLUMN reviews.external_user_id
IS 'ID of the end user provided by the client';
COMMENT ON COLUMN reviews.sport_id
IS 'ID of the sport this review is associated with; NULL indicates the review '
'is for the entire venue';
COMMENT ON COLUMN reviews.comment_content
IS 'Comment written by the end user.';
CREATE TRIGGER reviews_set_updated_at
BEFORE UPDATE ON reviews
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();


CREATE TABLE crowd_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT NOT NULL REFERENCES clients(id),
    external_user_id VARCHAR(128) NOT NULL,
    venue_id BIGINT NOT NULL REFERENCES venues(id),
    sport_id BIGINT REFERENCES sports(id),
    crowd_level VARCHAR(8) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT current_timestamp,

    CONSTRAINT crowd_reports_crowd_level_enum CHECK (crowd_level IN (
        'EMPTY',
        'LIGHT',
        'MODERATE',
        'BUSY',
        'PACKED'
    ))
);
COMMENT ON TABLE crowd_reports
IS 'Crowd-level observations submitted by end users for venues';
COMMENT ON COLUMN crowd_reports.client_id
IS 'Client that provides the report';
COMMENT ON COLUMN crowd_reports.external_user_id
IS 'ID of the end user provided by the client';
COMMENT ON COLUMN crowd_reports.sport_id
IS 'ID of the sport this report is associated with; NULL indicates the report '
'is for the entire venue';
COMMENT ON COLUMN crowd_reports.crowd_level
IS 'Level of crowdedness at the venue';
