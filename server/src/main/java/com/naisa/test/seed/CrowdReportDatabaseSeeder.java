package com.naisa.test.seed;

import java.util.ArrayList;
import java.util.List;

import jakarta.annotation.Priority;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.data.domain.Sort;
import org.springframework.stereotype.Component;

import com.naisa.constant.CrowdConstant;
import com.naisa.model.entity.Client;
import com.naisa.model.entity.CrowdReport;
import com.naisa.model.entity.VenueSport;
import com.naisa.repository.ClientRepository;
import com.naisa.repository.CrowdReportRepository;
import com.naisa.repository.VenueSportRepository;
import com.naisa.util.Beans;

import net.datafaker.Faker;

/**
 * Represents a crowd report database seeder, run after clients and venue sports are inserted.
 *
 * @author Vincent Lai, Codex
 */
@Component
@Priority(700)
public final class CrowdReportDatabaseSeeder extends DatabaseSeeder<CrowdReport> {
    private static final Logger LOGGER = LoggerFactory.getLogger(CrowdReportDatabaseSeeder.class);
    private static final List<String> CROWD_LEVELS = List.of(
        CrowdConstant.CROWD_LEVEL_EMPTY,
        CrowdConstant.CROWD_LEVEL_LIGHT,
        CrowdConstant.CROWD_LEVEL_MODERATE,
        CrowdConstant.CROWD_LEVEL_BUSY,
        CrowdConstant.CROWD_LEVEL_PACKED
    );

    private final ClientRepository clientRepository;
    private final VenueSportRepository venueSportRepository;
    private final CrowdReportRepository crowdReportRepository;

    public CrowdReportDatabaseSeeder(
        final ClientRepository clientRepository,
        final VenueSportRepository venueSportRepository,
        final CrowdReportRepository crowdReportRepository
    ) {
        super();
        this.clientRepository = clientRepository;
        this.venueSportRepository = venueSportRepository;
        this.crowdReportRepository = crowdReportRepository;
    }

    /**
     * Generates venue-wide and sport-specific crowd reports with valid crowd levels.
     *
     * <p>
     * Sport-specific reports use existing venue-sport pairs. Timestamps are generated by the
     * database.
     *
     * @param seed  the seed to use for random data generation
     * @param count the number of crowd reports to generate
     * @return the generated crowd reports
     * @author Vincent Lai, Codex
     */
    @Override
    public List<CrowdReport> generateEntities(final long seed, final int count) {
        final List<Client> clients = clientRepository.findAll(Sort.by("id"));
        final List<VenueSport> venueSports = venueSportRepository.findAll(Sort.by("id"));
        final Faker faker = getFaker(seed);

        final List<CrowdReport> crowdReports = new ArrayList<>();
        for (int i = 0; i < count; i++) {
            final Client client = faker.options().nextElement(clients);
            final VenueSport venueSport = faker.options().nextElement(venueSports);
            final String externalUserId = faker.regexify("[a-zA-Z0-9]{20}") + "-" + i;
            crowdReports.add(Beans.create(CrowdReport.class, it -> {
                it.setClient(client);
                it.setExternalUserId(externalUserId);
                it.setVenue(venueSport.getVenue());
                it.setSport(faker.bool().bool() ? venueSport.getSport() : null);
                it.setCrowdLevel(faker.options().nextElement(CROWD_LEVELS));
            }));
        }

        return crowdReports;
    }

    /**
     * Inserts the generated crowd reports into the database and logs the insertion.
     *
     * @param entities the crowd reports to insert
     * @author Vincent Lai, Codex
     */
    @Override
    public void seed(final List<CrowdReport> entities) {
        crowdReportRepository.saveAll(entities);
        LOGGER.info("Inserted {} seed crowd reports into the database.", entities.size());
    }
}
