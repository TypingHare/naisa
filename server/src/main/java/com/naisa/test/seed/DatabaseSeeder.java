package com.naisa.test.seed;

import java.util.Locale;
import java.util.Random;

import net.datafaker.Faker;

/**
 * Represents a database seeder.
 *
 * <p>
 * Concrete seeders must be registered as Spring beans and annotated with
 * {@link jakarta.annotation.Priority}. The test database runner invokes them in ascending priority
 * order, breaking ties by fully qualified class name.
 *
 * @author James Chen
 */
public abstract class DatabaseSeeder {
    /**
     * Inserts this seeder's initial data into the database.
     *
     * <p>
     * Implementations that generate random data should initialize their random generators with the
     * supplied seed to make generation repeatable. Values generated by the database are not
     * controlled by this seed.
     *
     * @param seed the seed to use for random data generation
     * @author James Chen
     */
    public abstract void seed(long seed);

    /**
     * Creates a faker object with a specified random seed.
     *
     * @param seed the seed to use for random data generation
     * @return a faker object created by the seed
     * @author James Chen
     */
    protected Faker getFaker(final long seed) {
        return new Faker(Locale.US, new Random(seed));
    }
}
