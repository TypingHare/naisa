package com.naisa.test.seed;

import java.util.ArrayList;
import java.util.List;

import jakarta.annotation.Priority;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.data.domain.Sort;
import org.springframework.stereotype.Component;

import com.naisa.model.entity.Client;
import com.naisa.model.entity.Review;
import com.naisa.model.entity.VenueSport;
import com.naisa.repository.ClientRepository;
import com.naisa.repository.ReviewRepository;
import com.naisa.repository.VenueSportRepository;
import com.naisa.util.Beans;

import net.datafaker.Faker;

/**
 * Represents a review database seeder, run after clients and venue sports are inserted.
 *
 * @author Vincent Lai, Codex
 */
@Component
@Priority(600)
public final class ReviewDatabaseSeeder extends DatabaseSeeder<Review> {
    private static final Logger LOGGER = LoggerFactory.getLogger(ReviewDatabaseSeeder.class);

    private final ClientRepository clientRepository;
    private final VenueSportRepository venueSportRepository;
    private final ReviewRepository reviewRepository;

    public ReviewDatabaseSeeder(
        final ClientRepository clientRepository,
        final VenueSportRepository venueSportRepository,
        final ReviewRepository reviewRepository
    ) {
        super();
        this.clientRepository = clientRepository;
        this.venueSportRepository = venueSportRepository;
        this.reviewRepository = reviewRepository;
    }

    /**
     * Generates venue-wide and sport-specific reviews with distinct external user IDs.
     *
     * <p>
     * Sport-specific reviews use existing venue-sport pairs. Timestamps are generated by the
     * database.
     *
     * @param seed  the seed to use for random data generation
     * @param count the number of reviews to generate
     * @return the generated reviews
     * @author Vincent Lai, Codex
     */
    @Override
    public List<Review> generateEntities(final long seed, final int count) {
        final List<Client> clients = clientRepository.findAll(Sort.by("id"));
        final List<VenueSport> venueSports = venueSportRepository.findAll(Sort.by("id"));
        final Faker faker = getFaker(seed);

        final List<Review> reviews = new ArrayList<>();
        for (int i = 0; i < count; i++) {
            final Client client = faker.options().nextElement(clients);
            final VenueSport venueSport = faker.options().nextElement(venueSports);
            final String externalUserId = faker.regexify("[a-zA-Z0-9]{20}") + "-" + i;
            reviews.add(Beans.create(Review.class, it -> {
                it.setClient(client);
                it.setExternalUserId(externalUserId);
                it.setVenue(venueSport.getVenue());
                it.setSport(faker.bool().bool() ? venueSport.getSport() : null);
                it.setRating((short) faker.number().numberBetween(1, 6));
                it.setCommentContent(faker.lorem().sentence());
            }));
        }

        return reviews;
    }

    /**
     * Inserts the generated reviews into the database and logs the insertion.
     *
     * @param entities the reviews to insert
     * @author Vincent Lai, Codex
     */
    @Override
    public void seed(final List<Review> entities) {
        reviewRepository.saveAll(entities);
        LOGGER.info("Inserted {} seed reviews into the database.", entities.size());
    }
}
